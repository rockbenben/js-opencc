import { ConverterFactoryWithSegmentation, ProtectedConverter, DictGroup, DictLike, parseOpenCCDict, reverseDictString } from "./core.js";
import { variants2standard, standard2variants, phraseDictDirection, segmentationDictsFor, LocaleCode, PhraseDictDirection } from "./presets.js";
// Loader map only (a few hundred bytes) — the dict payloads behind each thunk
// stay in their own lazily-imported chunks so bundlers fetch per-file on demand.
import { dictLoaders } from "./dict/index.js";

// Dict modules will be generated by sync-opencc script
// Import them dynamically or statically after running sync

/**
 * Converter options
 */
export interface ConverterOptions {
  /** Source locale code */
  from: LocaleCode;
  /** Target locale code */
  to: LocaleCode;
  /**
   * Whether to consider the custom CNTWPhrases dict (default: on when either
   * end is `twp`). `true` enables it only in the directions
   * `phraseDictDirection` supports; `false` disables it everywhere.
   */
  loadCustomPhrases?: boolean;
}

/**
 * Locale preset data containing dictionary groups
 */
export interface LocalePreset {
  from: Record<string, DictGroup>;
  to: Record<string, DictGroup>;
  /**
   * Dictionaries available to cut the input on, keyed by dict file name (the
   * names `segmentationDictsFor` returns, e.g. `STPhrases` / `TSPhrases`).
   * Optional: a preset without it simply does not segment.
   */
  segmentation?: Record<string, DictLike>;
}

/**
 * Create a Converter factory with locale preset
 * @param localePreset - Preset containing dictionary groups for each locale
 * @returns Converter factory function
 */
export function ConverterBuilder(localePreset: LocalePreset) {
  return function Converter(options: ConverterOptions): (input: string) => string {
    const dictGroups: DictGroup[] = [];

    // Add 'from' dictionaries (variant -> standard)
    if (options.from !== "t" && localePreset.from[options.from]) {
      dictGroups.push(localePreset.from[options.from]);
    }

    // Add 'to' dictionaries (standard -> variant)
    if (options.to !== "t" && localePreset.to[options.to]) {
      dictGroups.push(localePreset.to[options.to]);
    }

    // Segmentation needs a dictionary keyed in the INPUT's script, which a
    // caller-supplied preset may not carry. Cut only when the preset actually
    // has it; a preset without it keeps the old, unsegmented behaviour rather
    // than silently cutting on the wrong script.
    const segmentationFiles = segmentationDictsFor(options.from, options.to);
    const segmentation = segmentationFiles.map((name) => localePreset.segmentation?.[name]).filter((d): d is DictLike => d !== undefined);

    return ConverterFactoryWithSegmentation(segmentation.length ? segmentation : null, ...dictGroups);
  };
}

/**
 * Dictionary files for a conversion, GROUPED BY CONVERSION STEP.
 *
 * Returns `string[][]`: each inner array is one conversion step
 * (variant→standard, then standard→variant). Each step MUST be loaded into a
 * SINGLE merged trie so the trie's longest-match lets phrase dictionaries
 * (STPhrases, *RevPhrases) win over single-character dictionaries.
 *
 * Correct usage:
 *   ConverterFactory(...getDictFiles(from, to).map(group => buildTrieFromGroup(group)))
 *
 * Do NOT flatten the groups and run each file as its own group — that converts
 * characters first, so the phrase dict's source keys no longer exist and every
 * phrase dictionary becomes dead code (头发→頭發 instead of 頭髮). That flat-list
 * mental model is exactly what this grouped return type exists to prevent. If you
 * only need the flat file list (e.g. to know which dict files to bundle), call
 * `getDictFiles(from, to).flat()`.
 *
 * @throws {Error} if `from` or `to` is an unknown locale (i.e. not `'t'` and not
 *   a key of `variants2standard` / `standard2variants`).
 */
export function getDictFiles(from: LocaleCode, to: LocaleCode): string[][] {
  const groups: string[][] = [];

  if (from !== "t") {
    const fromFiles = variants2standard[from];
    // Reject unknown locales loudly instead of silently producing a converter
    // that skips the step (which would return partially/un-converted text).
    if (!fromFiles) throw new Error(`Unknown 'from' locale: ${from}`);
    if (fromFiles.length) groups.push(fromFiles);
  }

  if (to !== "t") {
    const toFiles = standard2variants[to];
    if (!toFiles) throw new Error(`Unknown 'to' locale: ${to}`);
    if (toFiles.length) groups.push(toFiles);
  }

  return groups;
}

/** Memo for the auto-loaded package dict — see `createConverter` for why. */
let packageProtectedDict: Promise<DictLike | undefined> | undefined;

/**
 * Try to auto-load the bundled `data/custom/ProtectedDict.txt`. Returns undefined in
 * browsers/Deno, on any I/O error, or when the file parses to zero entries.
 * Resolves via `import.meta.url` so it works in both source (tsx) and
 * built (dist) environments.
 */
async function tryLoadPackageProtectedDict(): Promise<DictLike | undefined> {
  try {
    const fsMod = await import("node:fs/promises");
    const urlMod = await import("node:url");
    // converter.{ts,js} is one level deep under (src|dist); data/ is sibling.
    const filePath = urlMod.fileURLToPath(new URL("../data/custom/ProtectedDict.txt", import.meta.url));
    const text = await fsMod.readFile(filePath, "utf8");
    const parsed = parseOpenCCDict(text);
    return parsed.length > 0 ? parsed : undefined;
  } catch {
    return undefined;
  }
}

/**
 * Load dictionaries and create a converter.
 *
 * @param options - Converter options (locale, optional flags)
 * @param protectedDict - Hard-override dictionary. Matches are masked with PUA
 *   placeholders before built-in conversion runs, then restored after — OpenCC
 *   built-in dictionaries never see or modify them. Highest priority.
 *
 *   If omitted, `createConverter` auto-loads the bundled `data/custom/ProtectedDict.txt`
 *   (Node-only convenience). Pass an explicit value (including `[]`) to bypass.
 *
 *   **Breaking change in v1.3.1:** Replaces v1.0.x's `customDict` (soft
 *   override). If you depended on chained A→B (custom) → B→C (standard),
 *   rewrite as A→C directly.
 */
export async function createConverter(
  options: ConverterOptions,
  protectedDict?: DictLike
): Promise<(input: string) => string> {
  // Warn JS callers still passing the removed v1.0.x option. TypeScript catches
  // this as an excess property, but JS users wouldn't see the breakage otherwise.
  if (options && typeof options === "object" && "applyCharFixes" in options) {
    console.warn(
      "[js-opencc] The `applyCharFixes` option was removed in v1.3.x. " +
        "CharFixes.txt is replaced by `protectedDict` (hard override) — see README migration section."
    );
  }
  // Auto-load bundled data/custom/ProtectedDict.txt if no explicit dict provided.
  // Memoized like innerConverterCache: the file ships with the package and never
  // changes at runtime, and re-reading it dominates everything else in a batch
  // (200 cached calls: 82ms re-reading vs 0.1ms with the read hoisted out).
  //
  // `=== undefined`, NOT a falsy check: the documented contract is "any explicit
  // second argument (including []) bypasses auto-load", and "" is an explicit
  // argument too (DictLike admits strings). A falsy check made "" auto-load while
  // [] bypassed — invisible while the shipped file is all-commented (auto-load
  // yields zero entries either way), diverging the moment a user edits the file.
  if (protectedDict === undefined) {
    if (!packageProtectedDict) packageProtectedDict = tryLoadPackageProtectedDict();
    protectedDict = await packageProtectedDict;
  }

  // Key on the resolved phrase direction, not the raw option: two calls that
  // differ only in an explicit flag matching the default share one converter.
  const phraseDir = phraseDictDirection(options.from, options.to, options.loadCustomPhrases);
  const key = `${options.from}|${options.to}|${phraseDir}`;
  let innerPromise = innerConverterCache.get(key);
  if (!innerPromise) {
    innerPromise = buildInnerConverter(options.from, options.to, phraseDir).catch((e) => {
      // Evict failed builds (e.g. a dict chunk 404 after a redeploy) so a later
      // call can retry instead of replaying the cached rejection forever.
      innerConverterCache.delete(key);
      throw e;
    });
    innerConverterCache.set(key, innerPromise);
  }
  const convert = await innerPromise;

  // User protectedDict wraps as outermost PROTECTED layer (highest priority).
  // Empty protection ([] / "") returns the cached inner converter directly.
  return protectedDict && protectedDict.length ? ProtectedConverter(protectedDict, convert) : convert;
}

// Inner converters are pure functions of (from, to, phraseDir) over static
// dict data — cache the BUILD PROMISE so concurrent calls (e.g. a batch
// converting N files) share one trie build instead of racing N of them.
// protectedDict varies per call and wraps outside the cache.
const innerConverterCache = new Map<string, Promise<(input: string) => string>>();

async function buildInnerConverter(from: LocaleCode, to: LocaleCode, phraseDir: PhraseDictDirection): Promise<(input: string) => string> {
  // Dict module strings ("k1 v1|k2 v2") go straight into the trie —
  // Trie.loadDict parses that format natively.
  const loadDict = async (name: string): Promise<string | null> => {
    const loader = dictLoaders[name];
    if (!loader) {
      console.warn(`Dictionary ${name} not found. Run 'npm run sync:opencc' first.`);
      return null;
    }
    return (await loader()).default;
  };

  // (a) Built-in dictionaries — loaded per conversion-step group from
  // getDictFiles. Each step is ONE merged trie so the trie's longest-match lets
  // phrase dictionaries win over single-char dictionaries; running each file as
  // its own group converts chars first and leaves the phrase dict's simplified
  // source keys gone (头发→頭發 instead of 頭髮). getDictFiles returns the groups
  // already shaped correctly — this loop just turns file names into dicts.
  const dictGroups: DictGroup[] = [];
  for (const fileGroup of getDictFiles(from, to)) {
    const group = (await Promise.all(fileGroup.map(loadDict))).filter((d): d is string => d !== null);
    if (group.length) dictGroups.push(group);
  }

  // (b) Segmentation dictionary. Cutting the input first keeps a later
  // conversion step from matching across a word boundary an earlier step set —
  // without it the regional vocabulary tables over-fire in context
  // (他优化了 → 他最佳化了 where OpenCC gives 他優化了). Empty for single-step
  // chains, which then take ConverterFactory's cheaper path.
  const segmentationFiles = segmentationDictsFor(from, to);
  const segmentation = segmentationFiles.length ? (await Promise.all(segmentationFiles.map(loadDict))).filter((d): d is string => d !== null) : [];

  // (c) Build the inner converter chain
  let convert = ConverterFactoryWithSegmentation(segmentation.length ? segmentation : null, ...dictGroups);

  // CNTWPhrases used to be unshifted as an ordinary FIRST trie group. That
  // shape had two failure modes, both found by probing every entry in context:
  //
  //   1. Its keys were not segmentation boundaries, so the cut could land
  //      inside one (人脸识别 → [人脸][识别]) and the entry never matched.
  //   2. Its OUTPUT was re-fed through the built-in steps, which re-converted
  //      pieces of it: 调制解调器 → 數據機 → TWPhrases hits 數據→資料 → 資料機.
  //      This one predates segmentation — it shipped wrong from the start.
  //
  // ProtectedConverter's masking already implements the semantics this dict
  // actually wants — match key, hide the span behind a PUA placeholder so the
  // whole inner pipeline (segmentation included) cannot see it, restore the
  // TARGET VALUE afterwards. Vocabulary override means override: nothing
  // downstream may re-chew the result. The user's own protectedDict still
  // wraps outermost, so its priority stays above this layer (inner masking
  // passes pre-existing PUA through untouched).
  if (phraseDir) {
    const phrases = await loadDict("CNTWPhrases");
    if (phrases) {
      convert = ProtectedConverter(phraseDir === "reverse" ? reverseDictString(phrases) : phrases, convert);
    }
  }

  return convert;
}

